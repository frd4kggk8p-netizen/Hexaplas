function normalizeVocabKey(str) {
  if (!str) return "";
  return str.toLowerCase()
    .replace(/^(der|die|das|ein|eine)\s+/i, "")
    .replace(/ä/g, "ae")
    .replace(/ö/g, "oe")
    .replace(/ü/g, "ue")
    .replace(/ß/g, "ss")
    .replace(/[^a-z]/g, "");
}

function normalizeVocabKeyWithoutParen(str) {
  if (!str) return "";
  const noParen = str.replace(/\s*\([^\)]*\)/g, "");
  return normalizeVocabKey(noParen);
}

function getVocabImage(r) {
  if (!r) return "";
  if (r.img) return r.img;
  
  // 1. Probar alemán directo y sin paréntesis
  const kDe = normalizeVocabKey(r.de);
  if (kDe && VOCAB_IMAGES[kDe]) return VOCAB_IMAGES[kDe];
  const kDeNoParen = normalizeVocabKeyWithoutParen(r.de);
  if (kDeNoParen && VOCAB_IMAGES[kDeNoParen]) return VOCAB_IMAGES[kDeNoParen];
  
  // 2. Probar inglés directo y sin paréntesis
  const kEn = normalizeVocabKey(r.en);
  if (kEn && VOCAB_IMAGES[kEn]) return VOCAB_IMAGES[kEn];
  const kEnNoParen = normalizeVocabKeyWithoutParen(r.en);
  if (kEnNoParen && VOCAB_IMAGES[kEnNoParen]) return VOCAB_IMAGES[kEnNoParen];
  
  return "";
}
